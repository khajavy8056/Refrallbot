// Run with NODE_PATH pointing at an installation of jsdom.
const assert = require('assert');
const fs = require('fs');
const { JSDOM } = require('jsdom');
const js = fs.readFileSync('public/assets/js/app.js', 'utf8');
const html = `<!doctype html><div class="layout"><button data-training-open>آموزش</button><a href="/admin/users">users</a></div>
<div class="training-overlay" data-training-overlay hidden><section data-training-window data-source="https://drive.google.com/file/d/example/preview" data-local="0" data-auto-open="0"><div data-training-drag><a href="#">download</a><button data-training-float>▣</button><button data-training-close>close</button></div><div data-training-media></div></section></div>`;
const dom = new JSDOM(html, { url: 'https://example.test/admin', runScripts: 'outside-only' });
const w = dom.window;
const style = w.document.createElement('style');
style.textContent = fs.readFileSync('public/assets/css/app.css', 'utf8');
w.document.head.appendChild(style);
w.eval(js);
const d = w.document;
const overlay = d.querySelector('[data-training-overlay]');
let fullscreenCalls = 0, exits = 0;
Object.defineProperty(d, 'fullscreenElement', { configurable: true, writable: true, value: null });
overlay.requestFullscreen = () => { fullscreenCalls++; d.fullscreenElement = overlay; return Promise.resolve(); };
d.exitFullscreen = () => { exits++; d.fullscreenElement = null; return Promise.resolve(); };
d.querySelector('[data-training-open]').click();
assert.equal(fullscreenCalls, 1, 'initial opening requests fullscreen');
assert.equal(overlay.hidden, false);
const video = d.querySelector('[data-training-media] iframe');
assert.ok(video && video.src.includes('drive.google.com'));
d.querySelector('[data-training-float]').click();
assert.ok(overlay.classList.contains('is-floating'));
assert.equal(exits, 1, 'floating exits fullscreen');
assert.strictEqual(video, d.querySelector('[data-training-media] iframe'), 'player is not recreated when floated');
assert.ok(d.querySelector('iframe.training-workspace'), 'panel workspace survives navigation');
assert.equal(d.querySelector('.layout').style.display, 'none');
assert.equal(w.sessionStorage.getItem('rb_training_float_v1'), '1');
const frame = d.querySelector('iframe.training-workspace');
const cw = frame.contentWindow;
cw.document.open(); cw.document.write(html); cw.document.close();
cw.eval(js);
assert.equal(cw.document.querySelector('[data-training-overlay]').hidden, true, 'child does not create another player');
cw.document.querySelector('[data-training-open]').click();
assert.ok(!overlay.classList.contains('is-floating'), 'child button opens parent player');
assert.strictEqual(video, d.querySelector('[data-training-media] iframe'));
d.querySelector('[data-training-float]').click();
cw.history.replaceState(null, '', '/admin/users?page=2');
frame.dispatchEvent(new w.Event('load'));
assert.equal(w.location.pathname + w.location.search, '/admin/users?page=2');
assert.strictEqual(video, d.querySelector('[data-training-media] iframe'), 'navigation does not reload player');
// The parent can be called by the same-origin child without constructing a second player.
w.RBTrainingShell.open();
assert.ok(!overlay.classList.contains('is-floating'));
assert.strictEqual(video, d.querySelector('[data-training-media] iframe'));
d.querySelector('[data-training-float]').click();
assert.equal(d.querySelectorAll('iframe.training-workspace').length, 1);
d.querySelector('[data-training-close]').click();
assert.equal(overlay.hidden, true);
assert.equal(w.getComputedStyle(overlay).display, 'none', 'closing a floated player hides its overlay');
assert.equal(d.querySelector('[data-training-media]').children.length, 0);
assert.equal(w.sessionStorage.getItem('rb_training_float_v1'), null);
console.log('Training UI: open, float, persistent player, restore and close passed');
w.close();
