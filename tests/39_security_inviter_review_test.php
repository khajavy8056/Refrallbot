<?php
declare(strict_types=1);
require_once __DIR__.'/bootstrap.php';
require_once __DIR__.'/lib.php';
use RB\Controllers\Admin\SecurityController;
use RB\Services\CommissionSettings;
use RB\Services\SecurityService;
use RB\Services\UserService;
use RB\Support\Database;
T::suite('بررسی رویداد امنیتی و انتساب به معرف');
$db=Database::instance(); $users=new UserService($db);
$role=$db->insert('admin_roles',['name'=>'Super','slug'=>'superadmin','permissions'=>'["*"]','created_at'=>now(),'updated_at'=>now()]);
$admin=$db->insert('admins',['name'=>'Admin','username'=>'security-test','password_hash'=>password_hash('test-password',PASSWORD_DEFAULT),'role_id'=>$role,'is_active'=>1,'created_at'=>now(),'updated_at'=>now()]);
$_SESSION['admin_id']=$admin; $_SESSION['admin_last_seen']=time(); $_SESSION['_csrf_token']=bin2hex(random_bytes(32));
$_SERVER['REQUEST_METHOD']='GET'; $_SERVER['REQUEST_URI']='/admin/security'; $_SERVER['HTTP_HOST']='test.example'; $_SERVER['HTTP_ACCEPT']='application/json';
CommissionSettings::saveVersion(['direct_reward'=>1000,'direct_enabled'=>1,'qualify_conditions'=>['joined']]);
$parent=$users->registerFromTelegram(['id'=>83900001,'first_name'=>'معرف تست'])['user'];
$child=$users->registerFromTelegram(['id'=>83900002,'first_name'=>'دعوت شده تست'],$parent['referral_code'])['user'];
$pid=(int)$parent['id'];$cid=(int)$child['id'];
$e1=SecurityService::log('referral_burst','medium',['count'=>20,'referrer_id'=>$pid],$cid);
$e2=SecurityService::log('duplicate_names','low',[],$cid);
$e3=SecurityService::log('referral_burst','medium',['referrer_id'=>$pid],$cid);
$before=(int)$users->find($pid)['wallet_balance'];
$render=static function():string { ob_start(); (new SecurityController())->index(); return (string)ob_get_clean(); };
$_GET=[]; $html=$render();
T::ok(str_contains($html,'معرف تست') && str_contains($html,'دعوت شده تست'),'نام دعوت‌شده و معرف در صف امنیت نمایش داده می‌شود');
T::ok(str_contains($html,'ثبت تخلف برای معرف'),'دکمه تأیید مقصد را روشن نمایش می‌دهد');
$review=static function(int $id,string $status,int $ref=0):array { $_POST=['status'=>$status,'expected_referrer'=>$ref]; ob_start(); (new SecurityController())->review(['id'=>$id]); return json_decode((string)ob_get_clean(),true) ?: []; };
$r=$review($e1,'confirmed',$pid);
T::eq(true,(bool)$r['ok'],'تخلف برای معرف تأیید شد');
T::eq($pid,(int)$db->value('SELECT responsible_user_id FROM security_events WHERE id = :id',['id'=>$e1]),'معرف به عنوان مسئول در رویداد ذخیره شد');
T::eq($cid,(int)$db->value('SELECT user_id FROM security_events WHERE id = :id',['id'=>$e1]),'کاربر اصلی رویداد از سابقه حذف نشد');
T::eq('suspicious',$users->find($pid)['status'],'معرف فعال مشکوک علامت خورد');
T::eq('active',$users->find($cid)['status'],'حساب دعوت‌شده تغییر نکرد');
T::eq($before,(int)$users->find($pid)['wallet_balance'],'کیف پول معرف تغییر نکرد');
$r=$review($e1,'confirmed',$pid);
T::eq(false,(bool)$r['ok'],'عملیات تکراری پذیرفته نمی‌شود');
T::eq(1,(int)$db->value("SELECT COUNT(*) FROM admin_activity_logs WHERE action = 'security.reviewed' AND entity_id = :id",['id'=>$e1]),'تصمیم فقط یک بار ثبت مدیریتی شد');
$r=$review($e2,'reviewed'); T::eq(true,(bool)$r['ok'],'بررسی عادی رویداد ثبت شد');
$_GET=[]; $html=$render();
T::eq(false,str_contains($html,'name="expected_referrer" value="'.$pid.'"') && str_contains($html,'/admin/security/'.$e1.'/review'),'مورد تأییدشده در صف پیش‌فرض نیست');
T::eq(false,str_contains($html,'/admin/security/'.$e2.'/review'),'مورد بررسی‌شده در صف پیش‌فرض نیست');
T::ok(str_contains($html,'/admin/security/'.$e3.'/review'),'رویداد باز باقی‌مانده در صف وجود دارد');
$_GET=['status'=>'confirmed']; $html=$render();
T::ok(str_contains($html,'مسئول ثبت‌شده') && str_contains($html,'معرف تست'),'تخلف در فیلتر تاریخچه با معرف ثبت‌شده قابل مشاهده است');
// A changed referrer must not cause an administrator to flag an unexpected person.
$other=$users->registerFromTelegram(['id'=>83900003,'first_name'=>'معرف دوم'])['user'];
$users->changeReferrer($cid,(int)$other['id'],'تغییر معرف تست',$admin);
$r=$review($e3,'confirmed',$pid);
T::eq(false,(bool)$r['ok'],'معرف تغییرکرده بدون بازبینی تازه علامت نمی‌خورد');
T::eq('active',$users->find((int)$other['id'])['status'],'معرف جدید ناخواسته مشکوک نشد');
T::eq('open',$db->value('SELECT status FROM security_events WHERE id = :id',['id'=>$e3]),'رویداد تغییر نیافته در صف باقی ماند');
$unrelated=SecurityService::log('card_reuse','high',[],$cid);
$r=$review($unrelated,'confirmed',(int)$other['id']);
T::eq(true,(bool)$r['ok'],'رویداد نامرتبط قابل تأیید است');
T::eq('active',$users->find((int)$other['id'])['status'],'تأیید کارت تکراری معرف را مشکوک نمی‌کند');
T::eq(null,$db->value('SELECT responsible_user_id FROM security_events WHERE id = :id',['id'=>$unrelated]),'برای رویداد نامرتبط مسئول دعوت ثبت نمی‌شود');
$none=SecurityService::log('referral_burst','high',[],$pid);
$r=$review($none,'confirmed',0);
T::eq(false,(bool)$r['ok'],'رویداد قدیمی بدون معرف زمان وقوع نیاز به بررسی دستی دارد');
// Confirming must not downgrade a blocked inviter to suspicious.
$users->setStatus((int)$other['id'],'blocked',$admin,'تست وضعیت مسدود');
$blockedEvent=SecurityService::log('referral_burst','medium',['referrer_id'=>(int)$other['id']],$cid);
$r=$review($blockedEvent,'confirmed',(int)$other['id']);
T::eq(true,(bool)$r['ok'],'تصمیم درباره معرف مسدود ثبت شد');
T::eq('blocked',$users->find((int)$other['id'])['status'],'حساب مسدود ناخواسته رفع انسداد نشد');
exit(T::summary());
